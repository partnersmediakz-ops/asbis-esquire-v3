/**
 * Произношение для озвучки.
 *
 * Словарь ударений Silero составлен для русских слов: латиницу модель либо
 * читает по буквам, либо угадывает — «LiDAR» превращается в набор звуков,
 * а «macOS» в «макос». Поэтому перед синтезом латинские названия заменяем
 * русской записью с ударением.
 *
 * Замена касается только произносимой строки. На экране остаётся исходное
 * написание: читатель видит «MacBook Neo», а слышит «макбу́к нэ́о».
 *
 * Знак «+» перед гласной — принятая в Silero пометка ударения.
 */
const DICTIONARY: Array<[RegExp, string]> = [
  // Порядок важен: составные названия идут раньше одиночных слов,
  // иначе «Apple Watch» распадётся на «Apple» и «Watch».
  [/\bApple\s+Watch\b/gi, 'Эпл В+отч'],
  [/\bMacBook\s+Neo\b/gi, 'Макб+ук Н+эо'],
  [/\bSmooth\s+Operator\b/gi, 'Смуз +Опер+эйтор'],
  [/\bAirPods\b/gi, 'Эйрп+одс'],
  [/\bMacBook\b/gi, 'Макб+ук'],
  [/\bmacOS\b/g, 'мак-о-+эс'],
  [/\biPhone\b/gi, 'Айф+он'],
  [/\biPad\b/gi, 'Айп+эд'],
  [/\bLiDAR\b/gi, 'Лид+ар'],
  [/\bApple\b/gi, 'Эпл'],
  [/\bEsquire\b/gi, 'Эскв+айр'],
  [/\bASBIS\b/gi, '+Асбис'],
];

/**
 * Граница слова для кириллицы.
 *
 * Обычный \b в JavaScript определён через \w, то есть только по латинице,
 * цифрам и подчёркиванию. Для русского слова он не срабатывает вовсе, и
 * замены молча не применяются — поэтому строим границы через свойства
 * Юникода.
 */
const word = (w: string) => new RegExp(`(?<!\\p{L})${w}(?!\\p{L})`, 'giu');

/**
 * Русские слова, где словарь ошибается или где ударение снимает
 * двусмысленность. Пополняется по итогам прослушивания.
 */
const STRESS: Array<[RegExp, string]> = [
  [word('бережет'), 'береж+ёт'],
  [word('посредников'), 'поср+едников'],
  [word('осязаемую'), 'осяз+аемую'],
];

// «все» намеренно не заменяется на «всё»: в тексте есть «все эти надписи»,
// где это множественное число, и слепая подстановка исказила бы смысл.
// Восстановлением «ё» занимается словарь модели, он смотрит на контекст.

/** Готовит строку к синтезу: латиница — по-русски, спорные ударения — явно. */
export function forSpeech(text: string): string {
  let out = text;
  for (const [pattern, replacement] of DICTIONARY) out = out.replace(pattern, replacement);
  for (const [pattern, replacement] of STRESS) out = out.replace(pattern, replacement);
  return out;
}

/** Есть ли в строке латиница, оставшаяся без замены. */
export function findUntranslated(text: string): string[] {
  return [...forSpeech(text).matchAll(/[A-Za-z]{2,}/g)].map((m) => m[0]);
}
