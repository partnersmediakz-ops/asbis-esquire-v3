import manifest from '../assets/figma/manifest.json';

const files = manifest as Record<string, string>;

/**
 * Описание по файлу кадра, а не только по узлу.
 *
 * Один и тот же снимок стоит в макете в нескольких узлах с разными id.
 * Описания составлены по сюжетам, то есть по файлам, поэтому дублирующий
 * узел должен получить то же описание — иначе часть фотографий уезжает
 * в вёрстку с пустым alt и пропадает для читателя скринридера.
 */
const byFile = new Map<string, string>();
for (const [nodeId, text] of Object.entries(ALTS)) {
  const file = files[nodeId];
  if (file && !byFile.has(file)) byFile.set(file, text);
}

/** Описание для узла. Без описания изображение считается декоративным. */
export function altFor(figmaId: string): string | null {
  const direct = ALTS[figmaId];
  if (direct) return direct;

  const file = files[figmaId];
  return (file && byFile.get(file)) ?? null;
}
